#!/usr/bin/env python3
"""生成 bass_chain_coeffs.h（低音链谐波生成用的 90 度移相网络系数）。

用法：
    python3 gen_bass_coeffs.py [输出路径]      # 默认写到本目录的 bass_chain_coeffs.h

需要 numpy 与 scipy。两串一阶全通 A(z) = (a + z^-1) / (1 + a z^-1)，在 HIL_BAND 内
两串的相位差为 90 度，给低频段求解析信号（谐波生成要用它的幅度和相位）。
频段只有几百赫兹、采样率 48 kHz，所以系数都贴着 -1，bass_chain.h 用双精度跑。

输出是确定性的（随机重启用固定种子）：同样的 numpy / scipy ⇒ 逐字节相同的头文件，
"仓库里的系数是不是这样算出来的"可以直接 diff 验证（numpy 2.5.4 / scipy 1.18.1 上核过）。
"""
import os
import sys

import numpy as np
from scipy import optimize

FS = 48000
HIL_BAND = (20.0, 400.0)
HIL_SECTIONS = 5

HERE = os.path.dirname(os.path.abspath(__file__))


def allpass_phase(a, w):
    """prod (a_i + e^-jw) / (1 + a_i e^-jw) 的展开相位。"""
    z1 = np.exp(-1j * w)
    h = np.ones_like(z1)
    for ai in a:
        h = h * (ai + z1) / (1 + ai * z1)
    return np.unwrap(np.angle(h))


def design_hilbert():
    f = np.geomspace(*HIL_BAND, 400)
    w = 2 * np.pi * f / FS

    # 一节的极点在 z = -a，低频段时紧贴 z = 1 内侧；a = exp(u) - 1 且 u 有界，
    # 保证每个 a 都落在 (-1, 0)。
    def coeffs(u):
        return np.exp(u) - 1

    def resid(u):
        a, b = coeffs(u[:HIL_SECTIONS]), coeffs(u[HIL_SECTIONS:])
        d = allpass_phase(a, w) - allpass_phase(b, w)
        return np.degrees(np.angle(np.exp(1j * (d - np.pi / 2))))

    # 初值：极点频率在比 HIL_BAND 稍宽的范围内等比分布，两串交错。
    fp = np.geomspace(HIL_BAND[0] / 2, HIL_BAND[1] * 2, 2 * HIL_SECTIONS)
    u0 = np.log(2 * np.pi * fp / FS)
    u0 = np.concatenate([u0[0::2], u0[1::2]])
    lo, hi = np.log(1e-6), np.log(0.9)
    best = None
    rng = np.random.default_rng(1)
    for _ in range(12):
        r = optimize.least_squares(resid, np.clip(u0, lo + 1e-9, hi - 1e-9), bounds=(lo, hi),
                                   method='trf', max_nfev=20000, x_scale=1.0)
        if best is None or r.cost < best.cost:
            best = r
        u0 = best.x + rng.normal(0, 0.1, len(u0))
    a, b = coeffs(best.x[:HIL_SECTIONS]), coeffs(best.x[HIL_SECTIONS:])
    return list(map(float, a)), list(map(float, b)), float(np.abs(resid(best.x)).max())


def num(v):
    return f'{v:.17g}'


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, 'bass_chain_coeffs.h')
    a, b, herr = design_hilbert()
    print(f'移相网络：{HIL_SECTIONS}+{HIL_SECTIONS} 节，最大相位误差 {herr:.3f} 度', file=sys.stderr)
    lines = [
        '/* Generated by gen_bass_coeffs.py -- do not edit. */',
        '#ifndef GAOKUN_BASS_CHAIN_COEFFS_H',
        '#define GAOKUN_BASS_CHAIN_COEFFS_H',
        '',
        'namespace gaokun {',
        'namespace bass_coeffs {',
        '',
        '/* 90-degree network, first-order allpass sections (a + z^-1) / (1 + a z^-1);',
        f' * phase difference 90 +/- {herr:.2f} deg over {HIL_BAND[0]:.0f}-{HIL_BAND[1]:.0f} Hz at {FS} Hz.',
        ' * Chain A gives the in-phase part, chain B the quadrature part. */',
        f'constexpr int kHilSections = {HIL_SECTIONS};',
        'constexpr double kHilA[kHilSections] = {' + ', '.join(map(num, a)) + '};',
        'constexpr double kHilB[kHilSections] = {' + ', '.join(map(num, b)) + '};',
        '',
        '}  // namespace bass_coeffs',
        '}  // namespace gaokun',
        '',
        '#endif  // GAOKUN_BASS_CHAIN_COEFFS_H',
        '',
    ]
    with open(out, 'w') as f:
        f.write('\n'.join(lines))


if __name__ == '__main__':
    main()
